namespace EDMWMapDesigner.Generation;

/// <summary>Current script attribution and ownership markers from earlier releases.</summary>
internal static class MapScriptBranding
{
    internal const string GeneratedMarker = "// Generated by EDMW Mod Studio";
    internal const string UpgradedMarker = "// Upgraded by EDMW Mod Studio";
    private const string LegacyGeneratedMarker = "// Generated by EDMW Map Designer";
    private const string LegacyUpgradedMarker = "// Upgraded by EDMW Map Designer";

    internal static bool HasGeneratedMarker(string script) =>
        script.Contains(GeneratedMarker, StringComparison.Ordinal) ||
        script.Contains(LegacyGeneratedMarker, StringComparison.Ordinal);

    internal static bool HasOwnershipMarker(string script) =>
        HasGeneratedMarker(script) ||
        script.Contains(UpgradedMarker, StringComparison.Ordinal) ||
        script.Contains(LegacyUpgradedMarker, StringComparison.Ordinal);
}
